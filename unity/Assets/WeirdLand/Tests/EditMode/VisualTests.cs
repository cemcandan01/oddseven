using System.Collections.Generic;
using System.Linq;
using NUnit.Framework;
using UnityEngine;
using WeirdLand.Core.Data;
using WeirdLand.Core.Duels;

namespace WeirdLand.Unity.Tests
{
    public class VisualTests
    {
        private static UiText _text;
        private readonly List<Object> _spawned = new List<Object>();

        [OneTimeSetUp]
        public void LoadText() => _text = GameDataProvider.Load(GameDataProvider.DataDirectory()).Text;

        [TearDown]
        public void Cleanup()
        {
            foreach (var o in _spawned)
                if (o != null) Object.DestroyImmediate(o);
            _spawned.Clear();
        }

        private T Spawn<T>(T prefab) where T : Component
        {
            var go = Object.Instantiate(prefab.gameObject);
            _spawned.Add(go);
            return go.GetComponent<T>();
        }

        [Test]
        public void HandLayout_FourCards_CenteredWithSpacing()
            => Assert.That(HandLayout.Positions(4, 200, 1200, 20).Select(v => v.x), Is.EqualTo(new[] { -330f, -110f, 110f, 330f }));

        [Test]
        public void HandLayout_EightCards_FitWithinMaxWidth()
        {
            var xs = HandLayout.Positions(8, 200, 1200, 20).Select(v => v.x).ToArray();
            Assert.That(xs.Max() + 100, Is.LessThanOrEqualTo(600.001f));
            Assert.That(xs.Min() - 100, Is.GreaterThanOrEqualTo(-600.001f));
            Assert.That(xs, Is.Ordered);
        }

        [Test]
        public void HandLayout_Zero_Empty() => Assert.That(HandLayout.Positions(0, 200, 1200, 20), Is.Empty);

        [Test]
        public void HandLayout_AllOnBaseline() => Assert.That(HandLayout.Positions(8, 200, 1200, 20).Select(v => v.y), Is.All.EqualTo(0f));

        [Test]
        public void Catalog_HasAllPrefabs()
        {
            // BuildAll is not called here: every test run would rewrite the committed prefabs and dirty git.
            // Prefabs are generated by `tools/unity.sh prefabs`; this test validates the committed catalog.
            var cat = VisualCatalog.Load();
            Assert.That(cat.Card, Is.Not.Null);
            Assert.That(cat.Fighter, Is.Not.Null);
            Assert.That(cat.StatusChip, Is.Not.Null);
            Assert.That(cat.Button, Is.Not.Null);
            Assert.That(cat.IntentBubble, Is.Not.Null);
            Assert.That(cat.Timings, Is.Not.Null);
        }

        [Test]
        public void CardView_Bind_ShowsPreviewAndDimsWhenUnplayable()
        {
            var cat = VisualCatalog.Load();
            var view = Spawn(cat.Card);
            var def = TestDecks.Card("Dmg", 1, CardRole.Attack, new EffectDef { Type = EffectType.Damage, Amount = 7 });
            var card = new CardInstance(def, false);

            view.Bind(card, new CardPreview(7, 0), false, _text, cat);

            Assert.That(view.Card, Is.SameAs(card));
            Assert.That(view.PreviewText.text, Is.EqualTo("Hasar 7"));
            Assert.That(view.Group.alpha, Is.EqualTo(0.5f));
            Assert.That(view.Button.interactable, Is.False);
            Assert.That(view.NameText.text, Is.EqualTo("Dmg"));
            Assert.That(view.CostText.text, Is.EqualTo("1"));
            Assert.That(view.RoleText.text, Is.EqualTo("Hücum"));
            Assert.That(view.Frame.color, Is.EqualTo(cat.AttackCard));
        }

        [Test]
        public void CardView_Bind_PlayableWithDamageAndBlock_TwoLines()
        {
            var cat = VisualCatalog.Load();
            var view = Spawn(cat.Card);
            var card = new CardInstance(TestDecks.Card("Both", 2, CardRole.Defense), false);

            view.Bind(card, new CardPreview(4, 5), true, _text, cat);

            Assert.That(view.PreviewText.text, Is.EqualTo("Hasar 4\nKoruma 5"));
            Assert.That(view.Group.alpha, Is.EqualTo(1f));
            Assert.That(view.Button.interactable, Is.True);
            Assert.That(view.Frame.color, Is.EqualTo(cat.DefenseCard));
        }

        [Test]
        public void CardView_Click_RaisesClicked()
        {
            var cat = VisualCatalog.Load();
            var view = Spawn(cat.Card);
            view.Bind(new CardInstance(TestDecks.Card("c", 1, CardRole.Both), false), new CardPreview(0, 0), true, _text, cat);
            CardView got = null;
            view.Clicked += v => got = v;

            view.Button.onClick.Invoke();

            Assert.That(got, Is.SameAs(view));
        }

        [Test]
        public void FighterView_StatusChips_FollowEnumOrder()
        {
            var view = Spawn(VisualCatalog.Load().Fighter);
            var s = new Dictionary<StatusId, int> { { StatusId.Tired, 1 }, { StatusId.Unbalanced, 2 } };

            view.SetStatuses(s, _text);

            Assert.That(view.Chips.Select(c => c.Label), Is.EqualTo(new[] { "Dengesiz 2", "Yorgun 1" }));
            Assert.That(view.Chips[0].Tooltip, Is.EqualTo(_text.Get(UiKeys.StatusDesc(StatusId.Unbalanced))));
        }

        [Test]
        public void FighterView_SetStatuses_ReplacesPreviousChips()
        {
            var view = Spawn(VisualCatalog.Load().Fighter);
            view.SetStatuses(new Dictionary<StatusId, int> { { StatusId.Tired, 1 }, { StatusId.Unbalanced, 2 } }, _text);

            view.SetStatuses(new Dictionary<StatusId, int> { { StatusId.Momentum, 3 }, { StatusId.Tired, 0 } }, _text);

            Assert.That(view.Chips.Select(c => c.Label), Is.EqualTo(new[] { "Momentum 3" }));
            Assert.That(view.GetComponentsInChildren<StatusChip>(true).Length, Is.EqualTo(1));
        }

        [Test]
        public void FighterView_BlockZero_Hidden()
        {
            var view = Spawn(VisualCatalog.Load().Fighter);
            view.SetBlock(3);
            Assert.That(view.BlockVisible, Is.True);
            Assert.That(view.BlockText.text, Is.EqualTo("3"));

            view.SetBlock(0);

            Assert.That(view.BlockVisible, Is.False);
        }

        [Test]
        public void FighterView_SetupAndHp_ShowsLabels()
        {
            var view = Spawn(VisualCatalog.Load().Fighter);
            view.Setup("Ali", "Kontrol", Color.red, true);
            view.SetHp(12, 30);
            view.SetBall(true);

            Assert.That(view.NameText.text, Is.EqualTo("Ali"));
            Assert.That(view.HpText.text, Is.EqualTo("Kontrol 12/30"));
            Assert.That(view.HpFraction, Is.EqualTo(0.4f).Within(1e-5f));
            Assert.That(view.BallVisible, Is.True);
            Assert.That(view.Body.localScale.x, Is.EqualTo(-1f));
            Assert.That(view.NumberAnchor, Is.Not.Null);
        }

        [Test]
        public void IntentBubble_Card_ShowsNameDamageAndStatus()
        {
            var view = Spawn(VisualCatalog.Load().IntentBubble);
            var v = new IntentView(IntentKind.Card, "tackle", "tackle", 7, 0,
                new[] { new StatusPreview(StatusId.Unbalanced, 1, true) }, null, null, 0);

            view.Show(v, _text);

            Assert.That(view.Text, Does.Contain("tackle"));
            Assert.That(view.Text, Does.Contain("7 hasar"));
            Assert.That(view.Text, Does.Contain("Dengesiz"));
            Assert.That(view.Text, Is.EqualTo("tackle\n7 hasar\nDengesiz"));
        }

        [Test]
        public void IntentBubble_Card_BlockAndStackedStatus()
        {
            var view = Spawn(VisualCatalog.Load().IntentBubble);
            var v = new IntentView(IntentKind.Card, "wall", "Duvar", 0, 6,
                new[] { new StatusPreview(StatusId.Momentum, 2, false) }, null, null, 0);

            view.Show(v, _text);

            Assert.That(view.Text, Is.EqualTo("Duvar\n6 koruma\nMomentum 2"));
        }

        [Test]
        public void IntentBubble_Pass_ShowsTargetAndPercent()
        {
            var view = Spawn(VisualCatalog.Load().IntentBubble);
            var v = new IntentView(IntentKind.Pass, null, null, 0, 0, new StatusPreview[0], "mate", "Mate", 0.72);

            view.Show(v, _text);

            Assert.That(view.Text, Is.EqualTo("Pas: Mate (%72)"));
        }

        [Test]
        public void IntentBubble_WaitAndHide()
        {
            var view = Spawn(VisualCatalog.Load().IntentBubble);
            view.Show(new IntentView(IntentKind.Wait, null, null, 0, 0, new StatusPreview[0], null, null, 0), _text);
            Assert.That(view.Text, Is.EqualTo("Bekliyor"));
            Assert.That(view.gameObject.activeSelf, Is.True);

            view.Hide();

            Assert.That(view.gameObject.activeSelf, Is.False);
            Assert.That(view.Text, Is.Empty);
        }

        [Test]
        public void AnimTimings_Of_MultipliesByScale()
        {
            var t = new AnimTimings { Scale = 0.01f };
            Assert.That(t.Of(t.Draw), Is.EqualTo(0.0025f).Within(1e-7f));
        }
    }
}
